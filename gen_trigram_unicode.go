//go:build ignore

// gen_trigram_unicode.go writes trigram_unicode_tables.go: the lowercase,
// White_Space and Punct-or-Symbol tables that TrigramIndex uses, frozen at
// Unicode 15.0.0 (#99). It reads the stdlib unicode package and aborts unless
// unicode.Version is "15.0.0". go1.26.9 is pinned only because its stdlib
// carries Unicode 15.0.0; any toolchain with that version gives the same
// output (Go 1.21-1.26):
//
//	GOTOOLCHAIN=go1.26.9 go generate ./...
//
// The //go:generate directive needs a POSIX env command. On Windows, run
// GOTOOLCHAIN=go1.26.9 go run gen_trigram_unicode.go by hand (in PowerShell,
// set $env:GOTOOLCHAIN first). The generator imports only the stdlib, so if
// go.mod ever requires a newer Go than go1.26.9, run it from a directory
// outside the module and copy the output in.
//
// When a Go release changes unicode.Version, TestTrigramUnicodeTablesMatchStdlib
// skips with a message: set trigramUnicodeStdlibDiffVersion to that version
// (or add a case for it) and commit its diff, like
// testdata/trigram-unicode/stdlib-17.0.0-diff.txt. These tables never
// change. A second table set needs a new trigram_unicode_version token, and
// every reader must be upgraded before any writer emits it (see
// trigramUnicodeVersion).
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"unicode"
)

const (
	wantVersion = "15.0.0"
	outFile     = "trigram_unicode_tables.go"
)

type lowerRange struct {
	lo, hi, stride uint32
	delta          int32
}

func main() {
	if unicode.Version != wantVersion {
		log.Fatalf("unicode.Version is %s, want %s; run GOTOOLCHAIN=go1.26.9 go generate ./...", unicode.Version, wantVersion)
	}

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by gen_trigram_unicode.go from Go's unicode tables (Unicode %s); DO NOT EDIT.\n\n", wantVersion)
	buf.WriteString("package gin\n\nimport \"unicode\"\n\n")
	buf.WriteString("type trigramLowerRange struct {\n\tLo, Hi, Stride uint32\n\tDelta          int32\n}\n\n")

	lower := lowerRanges()
	buf.WriteString("// trigramLowerRanges maps every rune >= 0x80 whose lowercase differs from\n")
	buf.WriteString("// itself: r in [Lo, Hi] with (r-Lo)%Stride == 0 lowers to r+Delta.\n")
	buf.WriteString("var trigramLowerRanges = [...]trigramLowerRange{\n")
	for _, e := range lower {
		fmt.Fprintf(&buf, "\t{Lo: 0x%04X, Hi: 0x%04X, Stride: %d, Delta: %d},\n", e.lo, e.hi, e.stride, e.delta)
	}
	buf.WriteString("}\n\n")

	writeRangeTable(&buf, "trigramSpaceTable", "White_Space runes (unicode.IsSpace).", unicode.IsSpace)
	writeRangeTable(&buf, "trigramPunctOrSymbolTable", "punctuation and symbol runes (unicode.IsPunct || unicode.IsSymbol).", func(r rune) bool {
		return unicode.IsPunct(r) || unicode.IsSymbol(r)
	})

	src, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatalf("format generated source: %v", err)
	}
	if err := os.WriteFile(outFile, src, 0o644); err != nil {
		log.Fatalf("write %s: %v", outFile, err)
	}
	log.Printf("wrote %s: %d lowercase ranges", outFile, len(lower))
}

// lowerRanges merges runes with equal lowercase deltas into stride-1 or
// stride-2 ranges. ASCII is handled by a fast path and is not emitted.
func lowerRanges() []lowerRange {
	var out []lowerRange
	for r := rune(0x80); r <= unicode.MaxRune; r++ {
		l := unicode.ToLower(r)
		if l == r {
			continue
		}
		u := uint32(r)
		d := int32(l - r)
		if n := len(out); n > 0 {
			last := &out[n-1]
			if last.delta == d {
				if last.lo == last.hi && (u == last.hi+1 || u == last.hi+2) {
					last.stride = u - last.hi
					last.hi = u
					continue
				}
				if u == last.hi+last.stride {
					last.hi = u
					continue
				}
			}
		}
		out = append(out, lowerRange{lo: u, hi: u, stride: 1, delta: d})
	}
	return out
}

type span struct{ lo, hi rune }

func spans(f func(rune) bool) []span {
	var out []span
	in := false
	var lo rune
	for r := rune(0); r <= unicode.MaxRune+1; r++ {
		v := r <= unicode.MaxRune && f(r)
		if v && !in {
			lo = r
		}
		if !v && in {
			out = append(out, span{lo, r - 1})
		}
		in = v
	}
	return out
}

func writeRangeTable(buf *bytes.Buffer, name, doc string, f func(rune) bool) {
	var r16, r32 []span
	latinOffset := 0
	for _, s := range spans(f) {
		switch {
		case s.hi <= 0xFFFF:
			r16 = append(r16, s)
			if s.hi <= unicode.MaxLatin1 {
				latinOffset++
			}
		case s.lo > 0xFFFF:
			r32 = append(r32, s)
		default:
			r16 = append(r16, span{s.lo, 0xFFFF})
			r32 = append(r32, span{0x10000, s.hi})
		}
	}

	fmt.Fprintf(buf, "// %s holds the %s\n", name, doc)
	fmt.Fprintf(buf, "var %s = &unicode.RangeTable{\n", name)
	if len(r16) > 0 {
		buf.WriteString("\tR16: []unicode.Range16{\n")
		for _, s := range r16 {
			fmt.Fprintf(buf, "\t\t{Lo: 0x%04X, Hi: 0x%04X, Stride: 1},\n", s.lo, s.hi)
		}
		buf.WriteString("\t},\n")
	}
	if len(r32) > 0 {
		buf.WriteString("\tR32: []unicode.Range32{\n")
		for _, s := range r32 {
			fmt.Fprintf(buf, "\t\t{Lo: 0x%04X, Hi: 0x%04X, Stride: 1},\n", s.lo, s.hi)
		}
		buf.WriteString("\t},\n")
	}
	fmt.Fprintf(buf, "\tLatinOffset: %d,\n", latinOffset)
	buf.WriteString("}\n\n")
	log.Printf("%s: %d R16 + %d R32 ranges", name, len(r16), len(r32))
}
